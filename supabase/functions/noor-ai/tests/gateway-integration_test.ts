import { assert, assertEquals } from './assert.ts';

/**
 * Tier B — the gateway integration tests. **All four §J authentication rows verified against a real
 * local gateway.**
 *
 * ════════════════════════════════════════════════════════════════════════════
 *  STATUS: §J.1, §J.2a, §J.2b and §J.2d — plus the separate CORS preflight, which
 *          is NOT one of the four authentication rows — have been executed against
 *          a real local Supabase Edge gateway (CLI 2.111.0, supabase-edge-runtime
 *          1.74.2) serving this repository's own `verify_jwt` declaration with no
 *          bypass flag. They pass, and every rejection was confirmed pre-handler.
 *  RUN AS: `tests/run-tier-b.ps1`, which brings up a disposable local stack, serves
 *          the function, and runs this suite with `NOOR_AI_GATEWAY_URL` and
 *          `NOOR_AI_LOCAL_GATEWAY_JWT_SECRET` set in the child process only.
 *          Without those variables the rows are reported ignored — never passed.
 * ════════════════════════════════════════════════════════════════════════════
 *
 * ── Why these cases cannot be moved into the pure tier ───────────────────────
 * `verify_jwt` is enforced by the **platform**, not by the handler. The documentation is explicit that
 * when the check fails "the platform returns a 401 error, and your code never executes". So the four rows below
 * are assertions about something that runs *before* any code in this repository — and a mock cannot stand in for
 * it, because mocking the gateway would mean writing the very component under test.
 *
 * §J is unusually clear about this, and it is why the rows are shaped the way they are:
 *
 *   • §J.1 — an unauthenticated request. "Deployed with `verify_jwt` enabled this is the **gateway's** platform
 *     401 and there is **no NoorLife `request_id`** — the test asserts that shape, not NoorLife's schema."
 *   • §J.2a — an invalid signature. "Asserted as 'a 401 with no provider call and no NoorLife body', **not** as
 *     NoorLife's error schema."
 *   • §J.2b — an expired token. "The producer is whichever runs first: the test accepts the gateway's platform
 *     shape **or** the handler's `unauthenticated`, because the documentation does not enumerate the gateway's
 *     per-claim checks." Observed: the **gateway** runs first, and the handler never starts.
 *   • §J.2d — this project's `sb_publishable_*` key sent as a bearer token. Per the documentation the platform
 *     "tries to parse it as a JWT and rejects the request with `Invalid JWT`", so it is "a
 *     **malformed-credential** rejection at the gateway and **does not** prove §D.4's check-6 role assertion".
 *
 * ── How §J.2b is signed without a key entering this repository ───────────────
 * This row was blocked for a long time, and the reason was real: an expired token only exercises §J.2b if it is
 * *correctly signed* — signed by the key the gateway actually trusts. A token signed by any other key is §J.2a,
 * which is a different row. The key that satisfies that condition lives in local CLI state, and §B.2's rule is
 * that no key material enters this repository.
 *
 * The rule is kept, in full. What changed is where the key is allowed to exist:
 *
 *   • the signing secret belongs to a **disposable local stack**, generated by `supabase start` and destroyed by
 *     `supabase stop --no-backup` in the same run. It is not the hosted project's key, and no hosted credential
 *     is read, needed or accepted here;
 *   • the harness captures it **without printing it** and hands it to this process through one environment
 *     variable, which it clears in a `finally`. It is never a command-line argument, never a file, never a
 *     fixture, never a log line and never committed;
 *   • the token is minted **inside this test process** from that value, used once against `127.0.0.1`, and
 *     discarded with the process.
 *
 * So the repository holds the *procedure*, and never the *material*. Reading this file tells you how the token
 * is produced; it does not tell you, and cannot be made to tell you, what it was signed with.
 *
 * ── Why the row needs a control request to mean anything ─────────────────────
 * A 401 on an expired token proves nothing on its own: a 401 is also what a wrong key, an unsupported algorithm
 * or a rejected issuer produces, and §J.2a already covers the wrong-key case. The assertion that the rejection
 * is *about `exp`* therefore rests on a paired control rather than on the response text:
 *
 *   • a **control** token — same key, same algorithm, same claims, `exp` in the future — is sent first. It gets
 *     through the gateway, and the reply is NoorLife's own envelope carrying a `request_id`, which only the
 *     handler can produce. That is what establishes the key is genuinely the one the gateway trusts;
 *   • the **expired** token — identical in every respect except `exp` — is refused with the platform's shape and
 *     no `request_id`, so the handler never ran.
 *
 * "Identical in every respect except `exp`" is a claim about the bytes, so the test proves it rather than
 * asserting it in prose. The shared claims are built **once** and both tokens are spread from that one object;
 * the signing helper generates nothing of its own — no uuid, no timestamp, no default — so it cannot introduce a
 * second variable; one frozen JOSE header object is passed to both; and before either token is signed the test
 * checks mechanically that the two claim sets carry the same keys in the same order, that exactly one key's
 * serialised value differs, and that the differing key is `exp`. An earlier revision minted a fresh `sub`,
 * `session_id` and `iat` per call, so the one-variable experiment it described was not the one it ran.
 *
 * Two requests differing in exactly one claim, with opposite outcomes. That is the evidence, and it does not
 * depend on reading a `code` string whose spelling is a runtime detail (§I.7).
 *
 * ── What the real gateway actually answered ──────────────────────────────────
 * Recorded because it differs from the documented shape, and §I.7 makes that AI-4's problem to absorb.
 * The hosted troubleshooting page documents a numeric `{ "code": 401, "message": … }`. Served locally,
 * supabase-edge-runtime 1.74.2 answers a **string** code and a duplicated message key:
 *
 *   §J.1   no Authorization       → 401 `{ "code": "UNAUTHORIZED_NO_AUTH_HEADER",     "message": …, "msg": … }`
 *   §J.2a  forged signature       → 401 `{ "code": "UNAUTHORIZED_ASYMMETRIC_JWT",     "message": …, "msg": … }`
 *   §J.2b  correctly signed, past → 401 `{ "code": "UNAUTHORIZED_LEGACY_JWT",         "message": …, "msg": … }`
 *   §J.2d  `sb_publishable_*`     → 401 `{ "code": "UNAUTHORIZED_INVALID_JWT_FORMAT", "message": …, "msg": … }`
 *   preflight `OPTIONS`           → 200, no credential required
 *
 * None of those is NoorLife's envelope and none carries a `request_id`, which is the property §C.9 relies on.
 * §J.2b's `code` is worth a second look: it names the *token family*, not the expiry, and it is the same family
 * the control token belongs to — so the code alone would not have distinguished the two. The control did. No
 * assertion below pins any of these spellings.
 *
 * That the rejections are genuinely pre-handler was confirmed independently of the body: the runtime logged each
 * failure from its own main worker, no `noor-ai` function worker booted for them, and the handler's single
 * structured log line never appeared. For §J.2b the runtime named the cause outright —
 * `code: "ERR_JWT_EXPIRED", claim: "exp", reason: "check_failed"` — while the control request in the same run
 * produced exactly one handler log line and a NoorLife body.
 *
 * ── The limit of what this tier shows ────────────────────────────────────────
 * This is evidence about a **local** gateway at the CLI and runtime versions named above. It is not proof of the
 * hosted project's behaviour, and the observed-shape divergence from the documented one is itself the reason to
 * keep that distinction: runtime version visibly matters. Deployment remains prohibited at this phase.
 *
 * ── How to run this tier ─────────────────────────────────────────────────────
 * `tests/run-tier-b.ps1` does all of it: Docker, the CLI, `supabase start`, `supabase functions serve`, this
 * suite with `--allow-net` scoped to the local gateway, then `supabase stop --no-backup`. Never
 * `--no-verify-jwt`: that flag would disable the single control this tier exists to test.
 *
 * They deliberately do **not** skip silently. A skipped test is invisible in a green run; a test that announces
 * "UNRUN — no local Supabase stack" is a line in the output that has to be read and answered for.
 */


// §J.2b — the one row that needs a correctly signed token
// ─────────────────────────────────────────────────────────────────────────────

/** RFC 7515 §2 base64url: unpadded, URL-safe. Written out because the JOSE segments must be exact. */
function base64Url(bytes: Uint8Array): string {
  let binary = '';
  for (const byte of bytes) {
    binary += String.fromCharCode(byte);
  }
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

/**
 * The complete claim set of a local gateway token, written in the order the claims are serialised.
 *
 * Declared as a type rather than assembled ad hoc so that both §J.2b tokens are demonstrably the same shape:
 * a missing or extra claim would be a second variable, and a second variable is what makes the row
 * inconclusive.
 */
type LocalTokenClaims = {
  readonly iss: string;
  readonly sub: string;
  readonly aud: string;
  readonly role: string;
  readonly session_id: string;
  readonly iat: number;
  readonly exp: number;
};

/**
 * The one JOSE header both §J.2b tokens are signed under.
 *
 * A single frozen object passed to both signings, so the header segment is identical by construction rather
 * than by two literals happening to agree.
 */
const LOCAL_TOKEN_HEADER: Readonly<Record<string, string>> = Object.freeze({
  alg: 'HS256',
  typ: 'JWT',
});

/**
 * Sign a caller-supplied header and claim set as an HS256 JWT for the disposable local gateway.
 *
 * This helper **generates nothing**: no uuid, no timestamp, no default, no `Date.now()`. Every byte of both
 * JOSE segments comes from its arguments, which is what allows the caller to state — and to check — that two
 * tokens differ in exactly one claim. An earlier version generated `sub`, `session_id` and `iat` internally,
 * so every call produced a token that differed from the last in four places while the comment claimed one.
 *
 * `secret` is the local stack's own signing secret, read from the environment by the caller and held only in
 * this process. Nothing here writes, logs or returns it, and the token it produces is used once.
 */
async function signLocalToken(
  secret: string,
  header: Readonly<Record<string, string>>,
  claims: LocalTokenClaims,
): Promise<string> {
  const encoder = new TextEncoder();
  const signingInput = `${base64Url(encoder.encode(JSON.stringify(header)))}.${
    base64Url(encoder.encode(JSON.stringify(claims)))
  }`;
  const key = await crypto.subtle.importKey(
    'raw',
    encoder.encode(secret),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign'],
  );
  const signature = new Uint8Array(
    await crypto.subtle.sign('HMAC', key, encoder.encode(signingInput)),
  );
  return `${signingInput}.${base64Url(signature)}`;
}

/**
 * The names of the claims whose serialised values differ between two claim sets.
 *
 * Returns key **names** only. No claim value, no serialised segment and no token leaves this function, so the
 * assertion built on it can report *which* claim varied without ever printing what it held.
 */
function differingClaimKeys(a: LocalTokenClaims, b: LocalTokenClaims): string[] {
  const left = a as unknown as Record<string, unknown>;
  const right = b as unknown as Record<string, unknown>;
  const keys = [...new Set([...Object.keys(left), ...Object.keys(right)])];
  return keys.filter((key) => JSON.stringify(left[key]) !== JSON.stringify(right[key]));
}

Deno.test({
  name:
    'TIER B — §J.2b a correctly signed token whose exp has passed is refused before the handler runs',
  /**
   * Two conditions, not one. The gateway alone is not enough for this row: without the disposable stack's
   * signing secret the best this could produce is a differently signed token, which is §J.2a wearing §J.2b's
   * name — the substitution that kept this row honestly blocked rather than quietly green.
   */
  ignore: GATEWAY_URL === null || LOCAL_SIGNING_SECRET === null,
  fn: async () => {
    const secret = LOCAL_SIGNING_SECRET as string;
    const origin = new URL(GATEWAY_URL as string).origin;
    const nowSeconds = Math.floor(Date.now() / 1000);

    /**
     * Everything the two tokens share, built once and read twice.
     *
     * One object, one `Date.now()`, one `randomUUID()` per claim. Both tokens are spread from this, so no
     * claim below can drift between them: there is only one value in existence for each.
     *
     * `iat` is deliberately older than either `exp` — an hour and two minutes back — so that both tokens are
     * internally coherent (issued, then expiring) and neither can be refused for an `iat` in the future. It is
     * the *same* `iat` for both, which is the point: the expired token is not "an older token", it is this
     * token with one field changed.
     */
    const commonClaims = {
      iss: `${origin}/auth/v1`,
      sub: crypto.randomUUID(),
      aud: 'authenticated',
      role: 'authenticated',
      session_id: crypto.randomUUID(),
      iat: nowSeconds - 3720,
    };
    const controlClaims: LocalTokenClaims = { ...commonClaims, exp: nowSeconds + 300 };
    const expiredClaims: LocalTokenClaims = { ...commonClaims, exp: nowSeconds - 3600 };

    /**
     * The one-variable experiment, checked before anything is signed.
     *
     * The whole row rests on the two requests differing in `exp` and in nothing else, and that is a property of
     * the bytes rather than of this comment. Three checks, none of which prints a claim value:
     *
     *   1. the same claim names in the same order, so `JSON.stringify` emits the same serialised layout;
     *   2. exactly one claim's serialised value differs, and it is `exp`;
     *   3. the serialised claim sets are byte-identical once `exp`'s digits are masked out — which is the
     *      direct statement of "only exp differs", made about the string that actually gets signed.
     *
     * If any of these fails the row stops here rather than sending a request it could not interpret.
     */
    assertEquals(
      Object.keys(controlClaims),
      Object.keys(expiredClaims),
      '§J.2b — both tokens must carry the same claim names in the same serialised order',
    );
    assertEquals(
      differingClaimKeys(controlClaims, expiredClaims),
      ['exp'],
      '§J.2b — the control and the expired claim set must differ in exactly one claim, and it must be exp',
    );
    const maskExp = (claims: LocalTokenClaims) =>
      JSON.stringify(claims).replace(/"exp":-?\d+/, '"exp":<varied>');
    assertEquals(
      maskExp(controlClaims) === maskExp(expiredClaims),
      true,
      '§J.2b — with exp masked the two serialised claim sets must be byte-identical',
    );

    /**
     * One frozen header object for both, and a helper that adds nothing of its own, so the only difference
     * that can reach the wire is the one asserted above.
     */
    const controlToken = await signLocalToken(secret, LOCAL_TOKEN_HEADER, controlClaims);
    const expiredToken = await signLocalToken(secret, LOCAL_TOKEN_HEADER, expiredClaims);
    /**
     * The same checks restated about the tokens themselves — compared as booleans, never as values, so no
     * serialised token can reach an assertion message or a failure report.
     */
    assertEquals(
      controlToken.split('.')[0] === expiredToken.split('.')[0],
      true,
      '§J.2b — both tokens must carry an identical JOSE header segment',
    );
    assertEquals(
      controlToken === expiredToken,
      false,
      '§J.2b — the two tokens must not be the same token',
    );

    /**
     * The control, and the reason this row means anything.
     *
     * Same key, same algorithm, same claims — `exp` in the future. If the gateway trusts this key, the request
     * gets past it and the reply is NoorLife's own envelope with a `request_id`, which only the handler can
     * produce. (The handler then refuses it on §D.6's documented grounds: it verifies against the platform's
     * asymmetric key set and cannot check an HS256 signature. A 401 either way — but a *NoorLife* 401.)
     *
     * If this assertion ever fails, the expired result below is uninterpretable and the row must be reported
     * inconclusive rather than passing: a 401 on the expired token would then be evidence of a rejected key
     * rather than of a rejected `exp`.
     */
    const control = await fetch(`${GATEWAY_URL}`, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        authorization: `Bearer ${controlToken}`,
      },
      body: JSON.stringify({ contract_version: 1, message: 'Where is Qibla?' }),
    });
    const controlBody = await control.json();
    assert(
      'request_id' in controlBody,
      'CONTROL: an unexpired token signed with the same key must reach the handler — without that, a 401 on ' +
        'the expired token proves nothing about exp, and this row is inconclusive rather than passing',
    );

    /**
     * The row itself: the same claim set with `exp` an hour in the past, and nothing else touched.
     */
    const response = await fetch(`${GATEWAY_URL}`, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        authorization: `Bearer ${expiredToken}`,
      },
      body: JSON.stringify({ contract_version: 1, message: 'Where is Qibla?' }),
    });

    assertEquals(response.status, 401, '§J.2b — an expired token is refused');
    const body = await response.json();

    /**
     * §J.2b permits either producer, so the assertion §J actually requires is the narrow one: no NoorLife
     * `request_id` may be *required*. What this gateway does is stronger, and it is asserted as observed —
     * the rejection is pre-handler, proved by the same property that separates the control from this request.
     */
    assertEquals(
      'request_id' in body,
      false,
      '§J.2b — refused before the handler, so no NoorLife request_id',
    );
    assertEquals('contract_version' in body, false, 'and not NoorLife’s envelope');
    assertEquals('error' in body, false, 'nor NoorLife’s nested error object');
    assert(
      typeof body.code === 'number' || (typeof body.code === 'string' && body.code.length > 0),
      'the platform shape carries a code, numeric or string',
    );

    /**
     * The discriminating assertion, stated as the comparison it is: the one claim that differed — proved to be
     * the only one, above, before either token was signed — flipped the outcome from "the handler answered" to
     * "the handler never ran". The response `code` is deliberately not pinned: §I.7 treats it as opaque, and
     * here it names the token family rather than the expiry, so it is the *pair* of results that identifies
     * `exp` as the cause, not the string.
     */
    assert(
      'request_id' in controlBody && !('request_id' in body),
      '§J.2b — exp was the only claim that differed between the two requests, and only the expired one was ' +
        'refused before the handler',
    );
  },
});


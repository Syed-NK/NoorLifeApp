/**
 * The runnable tier, which executes only when a gateway is actually there.
 *
 * `ignore` rather than an early `return`, so the runner reports these as ignored — visibly absent — rather than
 * as passing. A test that returns early on a missing precondition is a test that reads green while asserting
 * nothing, which is the specific outcome the phase brief forbids.
 */
Deno.test({
  name:
    'TIER B — §J.1 an unauthenticated request is refused by the gateway, in the platform’s shape',
  ignore: GATEWAY_URL === null,
  fn: async () => {
    const response = await fetch(`${GATEWAY_URL}`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ contract_version: 1, message: 'Where is Qibla?' }),
    });

    assertEquals(response.status, 401, '§J.1 — the gateway refuses it');
    const body = await response.json();
    // §C.9 — the platform shape, and NO NoorLife request_id, because the handler never ran.
    assertEquals('request_id' in body, false, 'no NoorLife request_id for a pre-handler rejection');
    assertEquals('contract_version' in body, false, 'and not NoorLife’s envelope either');
    assertEquals('error' in body, false, 'nor NoorLife’s nested error object');

    /**
     * `code` is asserted as present, not as the number 401 — and this is a correction, not a relaxation.
     *
     * The hosted troubleshooting page documents `{ "code": 401, … }`. A real local gateway
     * (supabase-edge-runtime 1.74.2) instead answers `{ "code": "UNAUTHORIZED_NO_AUTH_HEADER", … }`: a string.
     * The earlier `code === 401` assertion was an assumption about the platform, and it was wrong; pinning
     * either spelling now would assert a runtime version rather than the contract. What §C.9 and §I.7 actually
     * rely on is that the body is *not NoorLife's* and carries no `request_id`, which the three assertions
     * above check — and the discriminating ones were strengthened, not loosened, when this was fixed.
     */
    assert(
      typeof body.code === 'number' || (typeof body.code === 'string' && body.code.length > 0),
      'the platform shape carries a code, numeric or string',
    );
    assert(
      typeof body.message === 'string' && body.message.length > 0,
      'and a human-readable message',
    );
  },
});


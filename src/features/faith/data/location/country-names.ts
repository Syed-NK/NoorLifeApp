/**
 * ISO 3166-1 alpha-2 → the country name a search result shows.
 *
 * ── Why this is not in the catalogue asset ──────────────────────────────────
 * Because it is not GeoNames data. The importer reads `countryInfo.txt` only to *validate* that a
 * city's country code is real, and deliberately emits the two-letter code rather than a name: 34,084
 * rows carrying a repeated country string is the same 244 names written out tens of thousands of
 * times. Keeping the mapping here costs one small module and leaves the asset — whose bytes are
 * checksummed in `docs/THIRD_PARTY_LICENCES.md` — untouched.
 *
 * It also keeps the licence boundary clean. The city rows are CC BY 4.0 and carry GeoNames'
 * attribution; the standard English name of a country is not GeoNames' to license and is not claimed
 * as theirs.
 *
 * ── Why a code is never rendered on its own ─────────────────────────────────
 * "Dubai, Dubai, AE" is not a search result a person can scan. A user picking their city needs to see
 * the country, and two letters is a lookup they have to perform themselves — worse for exactly the
 * users who most need the list, who are searching for a city in a country they may not have a code
 * memorised for.
 *
 * ── Completeness is asserted, not assumed ───────────────────────────────────
 * `country-names.test.ts` walks every distinct country code in the shipped catalogue and fails if any
 * one of them is missing here. That is what makes `countryNameFor`'s fallback unreachable in
 * practice: it exists so a future catalogue re-import degrades to showing the code rather than
 * throwing or rendering "undefined", not as a state this build can reach.
 *
 * Names are the common English short forms — "Bolivia", not "Plurinational State of Bolivia" — which
 * is what belongs in a one-line result row.
 */


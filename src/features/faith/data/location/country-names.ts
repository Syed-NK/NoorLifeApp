/**
 * The country's name, falling back to the code itself.
 *
 * The fallback is unreachable for the shipped catalogue — the completeness test enforces that — and
 * exists so a re-import that introduced a new code would show `AQ` rather than `undefined`. Showing
 * the code is a worse row; showing a guessed country name would be a wrong one.
 */
export function countryNameFor(countryCode: string): string {
  return COUNTRY_NAMES[countryCode] ?? countryCode;
}
